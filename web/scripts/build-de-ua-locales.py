def main() -> None:
    with open(LOCALES / "en.json", encoding="utf-8") as f:
        en = json.load(f)
    with open(LOCALES / "ru.json", encoding="utf-8") as f:
        ru = json.load(f)

    de_out = deep_merge(en, DE)
    ua_out = deep_merge(ru, UA)
    # Ensure language labels and any EN-only keys from en
    ua_out = deep_merge(en, ua_out)

    for name, data in [("de", de_out), ("ua", ua_out)]:
        path = LOCALES / f"{name}.json"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"Wrote {path}")


